/** Idioma activo: el elegido en sesión, o DEFAULT_LANG si no eligió ninguno. */
function currentLang(): string
{
    $lang = $_SESSION['lang'] ?? DEFAULT_LANG;
    return isset(AVAILABLE_LANGS[$lang]) ? $lang : DEFAULT_LANG;
}

/**
 * Devuelve un string localizado por clave, en el idioma activo de la sesión.
 * Fallback: inglés → clave literal.
 */
function t(string $key): string
{
    global $LANG;
    $lang = currentLang();
    return $LANG[$lang][$key]
        ?? $LANG['en'][$key]
        ?? $key;
}

