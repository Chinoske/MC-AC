function renderLangSwitcher(): void
{
    $current = currentLang();

    $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $host   = $_SERVER['HTTP_HOST'] ?? '127.0.0.1:8080';
    $action = $scheme . '://' . $host . '/set_lang.php';

    $return = $_SERVER['REQUEST_URI'] ?? '/index.php';
    if (!str_starts_with($return, '/') || str_starts_with($return, '//') || str_contains($return, '://')) {
        $return = '/index.php';
    }
    ?>
    <form method="GET" action="<?= htmlspecialchars($action) ?>" class="lang-switcher">
        <input type="hidden" name="return" value="<?= htmlspecialchars($return) ?>">
        <select name="lang" onchange="this.form.submit()" aria-label="Idioma / Language">
            <?php foreach (AVAILABLE_LANGS as $code => $label): ?>
                <option value="<?= $code ?>" <?= $code === $current ? 'selected' : '' ?>>
                    <?= htmlspecialchars($label) ?>
                </option>
            <?php endforeach; ?>
        </select>
    </form>
    <?php
}








